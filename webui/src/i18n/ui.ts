/** 后端实体（场景 / 内置词库）按 id 取文案；没有对应文案时回落到接口返回的名称。 */
export function entityLabel(kind: "scene" | "bank", id: string, fallback: string): string {
  const key = `${kind}.${id}`;
  const text = t(key);
  return text === key ? fallback : text;
}

/** 带后缀的实体文案（如场景描述 scene.<id>.desc）；缺失时回落原文。 */
export function entityText(kind: "scene" | "cap", id: string, suffix: string, fallback: string): string {
  const key = `${kind}.${id}${suffix}`;
  const text = t(key);
  return text === key ? fallback : text;
}
